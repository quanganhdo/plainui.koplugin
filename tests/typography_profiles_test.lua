package.path = "./?.lua;./?/init.lua;" .. package.path
local Helper = require("tests.test_helper")
local test, run = Helper.newSuite()
local eq, truth = Helper.assertEqual, Helper.assertTruthy
local Profiles = require("modules.reader.typography_profiles")
local function settings(size, weight)
    return { font = "Noto Serif", size = size or 22, weight = weight or 0,
        spacing = 100, margins = { 10, 15 }, alignment = "auto" }
end
local function storage()
    return { data = {}, readSetting = function(self, key) return self.data[key] end,
        saveSetting = function(self, key, value) self.data[key] = value end,
        flush = function(self) self.flushed = true end }
end
local function fixture(current)
    local global, book = storage(), storage()
    return Profiles.new(global, book, settings(), current or settings()), global, book
end

test("new books follow the first profile without customization", function()
    local p = fixture()
    eq(p.active, 1); eq(p:profile().id, "default"); eq(p:profile().name, "Everyday")
    eq(p:isModified(), false); eq(p.book.variants.default.custom, nil)
end)
test("migration preserves every setting of an existing customized book", function()
    local p = fixture(settings(27, .75))
    truth(p:isModified()); eq(p.current.size, 27); eq(p.current.weight, .75)
    eq(p.current.margins[2], 15)
end)
test("book edits never modify the reusable profile or native defaults", function()
    local p, global = fixture()
    p:record(settings(26))
    truth(p:isModified()); eq(p:profile().settings.size, 22)
    eq(global.data[Profiles.GLOBAL_KEY].profiles[1].settings.size, 22)
    eq(global.data.copt_font_size, nil)
end)
test("switching profiles retains each book customization", function()
    local p = fixture()
    p:record(settings(24)); p:select(2, settings(24)); p:save("Large text", settings(28))
    p:record(settings(30)); p:select(1, settings(30))
    eq(p.current.size, 24); truth(p:isModified(2))
    p:select(2, settings(24)); eq(p.current.size, 30)
end)
test("the selected tab and inactive custom snapshots survive reopening", function()
    local p, global, book = fixture()
    p:record(settings(24)); p:select(3, settings(24)); p:save("Evening", settings(25))
    p:record(settings(26))
    local reopened = Profiles.new(global, book, settings(), settings(26))
    eq(reopened.active, 3); eq(reopened.current.size, 26); truth(reopened:isModified())
    reopened:select(1, settings(26)); eq(reopened.current.size, 24)
end)
test("reset removes the snapshot and resumes following the profile", function()
    local p = fixture()
    p:record(settings(30)); local result = p:reset()
    eq(result.size, 22); eq(p:isModified(), false); eq(p.book.variants.default.custom, nil)
end)
test("empty slots keep current appearance until explicitly saved", function()
    local p = fixture()
    local result = p:select(2, settings())
    truth(Profiles.equal(result, settings())); eq(p:profile().settings, nil)
    eq(p:reset(), nil); truth(p:isModified())
    p:save("Large", settings(29)); eq(p:isModified(), false)
end)
test("saving a profile updates followers on next open", function()
    local p, global = fixture()
    local follower_book = storage()
    Profiles.new(global, follower_book, settings(), settings())
    p:save("Everyday", settings(24, .5))
    local follower = Profiles.new(global, follower_book, settings(), settings())
    eq(follower.current.size, 24); eq(follower.current.weight, .5); eq(follower:isModified(), false)
end)
test("new books use the first profile even when its alignment differs from native defaults", function()
    local p, global = fixture()
    local preset = settings(); preset.alignment = "left"
    p:save("Everyday", preset)
    local fresh = Profiles.new(global, storage(), settings(), settings())
    eq(fresh.current.alignment, "left"); eq(fresh:isModified(), false)
end)
test("saving a profile leaves customized books completely unchanged", function()
    local p, global = fixture()
    local custom_book = storage()
    local custom = Profiles.new(global, custom_book, settings(), settings())
    custom:record(settings(27))
    p:save("Everyday", settings(24, 2))
    local reopened = Profiles.new(global, custom_book, settings(), settings(27))
    eq(reopened.current.size, 27); eq(reopened.current.weight, 0)
    eq(reopened.current.spacing, 100); eq(reopened.current.margins[2], 15)
end)
test("saving makes only the current book follow its new preset", function()
    local p = fixture()
    p:record(settings(30)); p:save("Everyday", settings(30))
    eq(p:isModified(), false); eq(p.book.variants.default.custom, nil)
end)
test("renaming uses stable IDs and does not replace settings", function()
    local p, global, book = fixture()
    p:record(settings(26)); truth(p:rename("Everyday"))
    eq(p:profile().settings.size, 22); eq(p.book.active, "default"); truth(p:isModified())
    local reopened = Profiles.new(global, book, settings(), settings(26))
    eq(reopened:profile().name, "Everyday"); eq(reopened.active, 1)
    truth(reopened:rename("Reading", 2)); eq(reopened.active, 1)
    eq(reopened:profile(2).name, "Reading")
end)
test("native KOReader changes are detected without overwriting profiles", function()
    local p, global, book = fixture()
    p = Profiles.new(global, book, settings(), settings(31, 1))
    truth(p:isModified()); eq(p.current.size, 31); eq(p:profile().settings.size, 22)
end)
test("returning manually to saved settings clears the marker", function()
    local p = fixture()
    p:record(settings(30)); p:record(settings()); eq(p:isModified(), false)
end)
test("profile and book tables do not alias stored snapshots", function()
    local p, global, book = fixture()
    local current = settings(24); p:record(current); current.margins[1] = 999
    eq(p.current.margins[1], 10); eq(book.data[Profiles.BOOK_KEY].variants.default.custom.margins[1], 10)
    p.store.profiles[1].settings.margins[1] = 888
    eq(global.data[Profiles.GLOBAL_KEY].profiles[1].settings.margins[1], 10)
end)
test("empty names cannot save or rename a profile", function()
    local p = fixture()
    eq(p:rename("  "), false); eq(p:save("  ", settings(30)), false)
    eq(p:profile().name, "Everyday"); eq(p:profile().settings.size, 22)
end)
run()
